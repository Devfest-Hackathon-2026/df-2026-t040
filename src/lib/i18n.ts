const dicts: Record<string, Dict> = { ja, en, zh: zh, 'zh-Hans': zh, 'zh-Hant': zh, ko, es, th }
export const t = (lang: string): Dict => dicts[lang] ?? dicts[lang.split('-')[0]] ?? en
export type { Dict }

export function langName(code: string, inLang = 'ja'): string {
  try {
    return new Intl.DisplayNames([inLang], { type: 'language' }).of(code) ?? code
  } catch {
    return code
  }
}

export function browserLang(): string {
  const l = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase()
  if (l.startsWith('zh')) return /hant|tw|hk|mo/.test(l) ? 'zh-Hant' : 'zh-Hans'
  if (l.startsWith('pt')) return l === 'pt-pt' ? 'pt-PT' : 'pt-BR'
  return l.split('-')[0]
}

